"""fb2parser_core.filename_stem.normalize_stem — разделитель автора в имени файла."""
import pytest

from fb2parser_core.filename_stem import normalize_stem


@pytest.mark.parametrize("stem, expected", [
    # Баг №127: дефис приклеен к точке инициала
    ("Ахманов М.- Миссия Тревельяна 1. Посланец небес",
     "Ахманов М. - Миссия Тревельяна 1. Посланец небес"),
    # Баг №134: длинное/среднее тире после имени автора
    ("Тамоников Александр — Группа Глеба Шубина 11. Танковая буря",
     "Тамоников Александр - Группа Глеба Шубина 11. Танковая буря"),
    ("Головачев В. — Атлантарктида", "Головачев В. - Атлантарктида"),
    ("Казакова Екатерина, Харитонова Алёна – Ходящие в ночи 1. Жнецы",
     "Казакова Екатерина, Харитонова Алёна - Ходящие в ночи 1. Жнецы"),
    ("Сен-Жюст Антуан — Речь", "Сен-Жюст Антуан - Речь"),
])
def test_author_separator_normalized(stem, expected):
    assert normalize_stem(stem) == expected


@pytest.mark.parametrize("stem", [
    # тире внутри названия — перед ним точки-разделители и цифры
    "Перумов. Летописи Разлома 3. Дочь Некроманта. Война мага. Дебют — Миттельшпиль",
    "1. Война — дело молодых",
    # «Фамилия. Название – продолжение» — точка не после инициала
    "Курниаван. Красота – это горе",
    "Волынская. Ирка Хортица – суперведьма (1-4 книги)",
    "Обычное имя - Без изменений 2. Книга",
    "Книга без разделителей",
])
def test_dash_inside_title_untouched(stem):
    assert normalize_stem(stem) == stem
