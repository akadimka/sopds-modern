"""Регрессия для `Pass4Consensus.execute()` (унификация автора по серии с
общим соавтором) — docs/quality-roadmap.md, баг №72.

Реальный случай (замечен пользователем в превью компилятора): Барчук
Павел, Ларин Павел / "ОБХСС" — трилогия физически задублирована в 4
папках, по одной на каждого соавтора отдельно ("Барчук Павел\ОБХСС..." и
"Ларин Павел\ОБХСС..."). `author_source=folder_dataset` режет
`<author>`-метаданные до ОДНОГО имени — имени папки, хотя метаданные
КАЖДОГО файла (без исключения, без межфайлового сравнения) уже
согласованно перечисляют ОБОИХ соавторов. Существующая унификация автора
по серии с общим токеном ("Барчук Павел" ⊂ "Барчук Павел, Прядеев
Евгений") отказывалась трогать `folder_dataset`-записи вовсе — и не
умела ОБЪЕДИНЯТЬ два РАВНОЗНАЧНЫХ по числу токенов варианта
("Барчук Павел" и "Ларин Павел", 2 токена каждый, не подмножество друг
друга) в общий "Барчук Павел, Ларин Павел".
"""
from fb2parser_core.logger import Logger
from fb2parser_core.passes.pass1_read_files import BookRecord
from fb2parser_core.passes.pass4_consensus import Pass4Consensus
from fb2parser_web.fb2parser_bridge import _config_path


def _rec(path, author, meta_authors):
    return BookRecord(
        file_path=path, file_title=path, metadata_authors=meta_authors,
        proposed_author=author, author_source="folder_dataset",
        metadata_series="ОБХСС", proposed_series="ОБХСС", series_source="folder_dataset",
        series_number="1",
    )


def _settings():
    from fb2parser_core.settings_manager import SettingsManager
    return SettingsManager(_config_path())


class TestFolderDatasetAuthorWidenedByOwnMetadataConfirmation:
    def test_peer_single_names_merged_when_own_metadata_confirms_both(self):
        _META = "Павел Барчук; Павел Ларин"
        records = [
            _rec(r"Барчук Павел\ОБХСС\01.fb2", "Барчук Павел", _META),
            _rec(r"Барчук Павел\ОБХСС\02.fb2", "Барчук Павел", _META),
            _rec(r"Ларин Павел\ОБХСС\01.fb2", "Ларин Павел", _META),
            _rec(r"Ларин Павел\ОБХСС\02.fb2", "Ларин Павел", _META),
        ]

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        assert all(r.proposed_author == "Барчук Павел, Ларин Павел" for r in records)

    def test_single_name_not_widened_without_own_metadata_confirmation(self):
        # Sanity: если у КОНКРЕТНОЙ записи метаданные НЕ подтверждают
        # объединённую форму (например, реальный разнобой — где-то в
        # серии метаданные другого автора вообще без Ларина), эта запись
        # не должна расширяться на основании чужих файлов.
        records = [
            _rec(r"Барчук Павел\ОБХСС\01.fb2", "Барчук Павел", "Павел Барчук"),
            _rec(r"Ларин Павел\ОБХСС\01.fb2", "Ларин Павел", "Павел Барчук; Павел Ларин"),
        ]

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        assert records[0].proposed_author == "Барчук Павел"

    def test_widened_even_without_a_second_copy_under_the_other_coauthor(self):
        # Реальный случай — "СМЕРШ" (Барчук, Ларин): существует только под
        # ОДНОЙ папкой автора, нет копии под именем второго соавтора — во
        # всём бакете серии единственный proposed_author = "Барчук Павел"
        # (нет расхождения вариантов вовсе). Метаданные ОБОИХ файлов
        # (100% большинство) уже согласованно говорят про соавторство —
        # этого достаточно, кросс-папочный дубль не нужен.
        _META = "Павел Барчук; Павел Ларин"
        records = [
            _rec(r"Барчук Павел\СМЕРШ\01.fb2", "Барчук Павел", _META),
            _rec(r"Барчук Павел\СМЕРШ\02.fb2", "Барчук Павел", _META),
        ]

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        assert all(r.proposed_author == "Барчук Павел, Ларин Павел" for r in records)

    def test_middle_name_in_metadata_dropped_not_left_unreordered(self):
        # Реальный случай — "Завод" (Гуров, Дамиров): метаданные первого
        # автора несут отчество ("Валерий Александрович Гуров" — Имя
        # Отчество Фамилия, 3 слова), второго — без ("Рафаэль Дамиров" —
        # 2 слова). Конвертер разворачивал в "Фамилия Имя" только РОВНО
        # двухсловные варианты — трёхсловный возвращался БЕЗ изменений,
        # давая испорченный порядок "Валерий Александрович Гуров, Дамиров
        # Рафаэль" (первый автор не развёрнут, второй — развёрнут).
        records = [
            _rec(r"Гуров Валерий\Завод\01.fb2", "Гуров Валерий",
                 "Валерий Александрович Гуров; Рафаэль Дамиров"),
            _rec(r"Гуров Валерий\Завод\02.fb2", "Гуров Валерий",
                 "Валерий Александрович Гуров; Рафаэль Дамиров"),
        ]

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        assert all(r.proposed_author == "Гуров Валерий, Дамиров Рафаэль" for r in records)

    def test_noisy_minority_metadata_does_not_widen_majority_clean_series(self):
        # Реальный случай (баг №58, отдельная реальная библиотека):
        # "Владимир Малый, Тёмные Окна - Сборник произведений" — 1 файл из
        # 6 несёт побочный, шумный <author> "Тёмные Окна" (имя вселенной,
        # ошибочно затянутое как соавтор), остальные 5 — честно только
        # "Владимир Малый". Наивное доверие метаданным ОДНОЙ записи
        # расширило бы автора и здесь — большинство (5 "чистых" против 1
        # "шумного") должно защитить от этого.
        records = [
            _rec(r"Владимир Малый\01.fb2", "Малый Владимир", "Владимир Малый"),
            _rec(r"Владимир Малый\02.fb2", "Малый Владимир", "Владимир Малый"),
            _rec(r"Владимир Малый\03.fb2", "Малый Владимир", "Владимир Малый"),
            _rec(r"Владимир Малый\04.fb2", "Малый Владимир", "Владимир Малый"),
            _rec(r"Владимир Малый\05.fb2", "Малый Владимир", "Владимир Малый"),
            _rec(r"Владимир Малый\06.fb2", "Малый Владимир", "Тёмные Окна; Владимир Малый"),
        ]
        for r in records:
            r.proposed_series = "Владимир Малый"

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        assert all(r.proposed_author == "Малый Владимир" for r in records)

    def test_unrelated_authors_sharing_a_series_name_not_cross_contaminated(self):
        # Реальная опасность на ПОЛНОЙ библиотеке (замечено пользователем):
        # группировка по имени серии не привязана к автору — два СОВЕРШЕННО
        # РАЗНЫХ, никак не связанных автора могут делить одно и то же
        # (родовое/короткое) имя серии. Раньше на шаге применения
        # проверялось только "есть ли у записи вообще какой-то кандидат
        # соавторства", а не "совпадает ли ЕЁ кандидат с победившим" —
        # победивший (по числу голосов) кандидат ОДНОЙ пары авторов мог
        # быть присвоен записям СОВЕРШЕННО ДРУГОГО, не связанного автора.
        records = [
            # Автор А: 1 запись, её собственный кандидат — "Смирнов Иван,
            # Кузнецов Олег" (1 голос).
            _rec(r"Смирнов Иван\Хроники\01.fb2", "Смирнов Иван",
                 "Иван Смирнов; Олег Кузнецов"),
            # Автор Б: 2 НИКАК не связанных с А записи, их кандидат —
            # "Волков Сергей, Лисицына Анна" (2 голоса — победитель).
            _rec(r"Волков Сергей\Хроники\01.fb2", "Волков Сергей",
                 "Сергей Волков; Анна Лисицына"),
            _rec(r"Волков Сергей\Хроники\02.fb2", "Волков Сергей",
                 "Сергей Волков; Анна Лисицына"),
        ]

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        # Автор А должен остаться со СВОИМ кандидатом (или как есть),
        # а не получить имена автора Б только потому, что тот выиграл
        # голосование В ТОЙ ЖЕ, случайно совпавшей по имени, серии.
        assert records[0].proposed_author != "Волков Сергей, Лисицына Анна"
        assert "Смирнов" in records[0].proposed_author

    def test_author_folder_root_set_for_all_records_including_unwidened_minority(self):
        # Реальный случай (Маркова Юлия, Михайловский Александр / "В
        # закоулках мироздания"): 16 из 18 файлов честно несут ОБОИХ
        # соавторов в метаданных (расширяются, как обычно), а 2 файла
        # (14, 17) в СВОИХ метаданных указывают только Михайловского —
        # эти два по политике "не трогаем без своего подтверждения"
        # proposed_author не меняют. Но author_folder_root (стабильное
        # имя папки при синхронизации, docs/quality-roadmap.md, баг №109)
        # должен получить победивший консенсус ВСЕМ 18 записям одинаково
        # — иначе серия физически раскидывается по двум разным папкам
        # автора в библиотеке (это и было настоящей причиной "файл
        # потерялся", замеченной пользователем).
        _META = "Александр Михайловский; Юлия Маркова"
        records = [
            _rec(rf"В закоулках мироздания\{n:02d}.fb2", "Михайловский Александр", _META)
            for n in range(1, 17)
        ] + [
            # 2 файла с неполными метаданными — только один автор.
            _rec(r"В закоулках мироздания\17.fb2", "Михайловский Александр",
                 "Александр Михайловский"),
            _rec(r"В закоулках мироздания\18.fb2", "Михайловский Александр",
                 "Александр Михайловский"),
        ]

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        widened = records[:16]
        unwidened = records[16:]
        assert all(r.proposed_author == "Маркова Юлия, Михайловский Александр" for r in widened)
        assert all(r.proposed_author == "Михайловский Александр" for r in unwidened)
        # Ключевая проверка: author_folder_root одинаков у ВСЕХ 18, включая
        # те 2, чей proposed_author не тронут.
        assert all(r.author_folder_root == "Маркова Юлия, Михайловский Александр" for r in records)

    def test_same_person_different_word_order_not_treated_as_coauthors(self):
        # Баг №109 (продолжение): "Роман Суржиков - Сборник произведений\
        # Полари" — часть файлов даёт proposed_author="Роман Суржиков"
        # (folder_dataset), часть — "Суржиков Роман" (тот же человек, имя
        # и фамилия просто переставлены местами). Оба варианта имеют
        # ОДИНАКОВОЕ число токенов (2) и НЕ являются подмножеством друг
        # друга по строгому сравнению множеств слов... но токены-то у них
        # буквально ОДИНАКОВЫЕ ({"роман", "суржиков"}) — это одна и та же
        # персона, а не два соавтора. Ветка бага №72 (ниже) предполагала,
        # что "одинаковое число токенов + не подмножество" всегда значит
        # "разные люди, делящие общий токен" и склеивала оба варианта
        # через запятую — "Роман Суржиков, Суржиков Роман" — для ВСЕХ
        # записей серии.
        records = [
            _rec(rf"Полари\{n}.fb2", "Роман Суржиков", "Роман Евгеньевич Суржиков")
            for n in range(1, 6)
        ] + [
            _rec(r"Полари\6.fb2", "Суржиков Роман", "Роман Евгеньевич Суржиков"),
        ]

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        for r in records:
            assert r.proposed_author in ("Роман Суржиков", "Суржиков Роман")
            assert "," not in r.proposed_author

    def test_metadata_series_bracket_suffix_does_not_block_widening(self):
        # Реальный случай — "СМЕРШ" (Барчук, Ларин): metadata_series одной
        # записи — "СМЕРШ [Барчук, Ларин]" (с уточнением в скобках),
        # другой — голое "СМЕРШ". Защитная проверка "разные произведения
        # под одним именем серии" сравнивала metadata_series БУКВАЛЬНО,
        # без отбрасывания такой пометки — из-за чего решала, что это два
        # разных произведения, и отказывалась расширять автора вовсе.
        records = [
            _rec(r"Барчук Павел\СМЕРШ\01.fb2", "Барчук Павел",
                 "Павел Барчук; Павел Ларин"),
            _rec(r"Барчук Павел\СМЕРШ\02.fb2", "Барчук Павел",
                 "Павел Барчук; Павел Ларин"),
        ]
        records[0].metadata_series = "СМЕРШ [Барчук, Ларин]"
        records[1].metadata_series = "СМЕРШ"

        Pass4Consensus(Logger(), settings=_settings()).execute(records)

        assert all(r.proposed_author == "Барчук Павел, Ларин Павел" for r in records)
