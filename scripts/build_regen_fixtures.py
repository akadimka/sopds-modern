_BODY_RE = re.compile(r"<body\b[^>]*>.*?</body>", re.DOTALL | re.IGNORECASE)
_BINARY_RE = re.compile(r"<binary\b[^>]*>.*?</binary>", re.DOTALL | re.IGNORECASE)
_body_counter = [0]


def _stub_body(match: "re.Match") -> str:
    tag_open = match.group(0).split(">", 1)[0] + ">"
    _body_counter[0] += 1
    return (
        f"{tag_open}<title><p>Fixture stub {_body_counter[0]}</p></title>"
        f"<p>Тестовый текст для fixture-набора regen_csv. Не является "
        f"реальным содержимым книги.</p></body>"
    )


def strip_fb2(text: str) -> str:
    _body_counter[0] = 0
    text = _BINARY_RE.sub("", text)
    text = _BODY_RE.sub(_stub_body, text)
    return text


def main():
    if len(sys.argv) != 2:
        print("Использование: python scripts/build_regen_fixtures.py <путь_к_библиотеке>")
        sys.exit(1)
    src_root = Path(sys.argv[1])

    if DST_ROOT.exists():
        shutil.rmtree(DST_ROOT)
    DST_ROOT.mkdir(parents=True)

    total_files = 0
    total_in = 0
    total_out = 0
    for rel, limit, recursive in SOURCES:
        src_dir = src_root / rel
        if not src_dir.is_dir():
            print("MISSING SOURCE:", src_dir)
            continue
        fb2_files = sorted((src_dir.rglob if recursive else src_dir.glob)("*.fb2"))
        if isinstance(limit, (list, tuple)):
            fb2_files = [f for f in fb2_files if f.name in limit]
            missing = set(limit) - {f.name for f in fb2_files}
            if missing:
                print("MISSING FILES in", rel, ":", sorted(missing))
        elif limit:
            fb2_files = fb2_files[:limit]
        dst_dir = DST_ROOT / rel
        dst_dir.mkdir(parents=True, exist_ok=True)
        for f in fb2_files:
            raw_bytes = f.read_bytes()
            enc_m = re.search(rb'encoding\s*=\s*["\']([^"\']+)["\']', raw_bytes[:256], re.IGNORECASE)
            declared_enc = enc_m.group(1).decode("ascii", errors="ignore") if enc_m else "utf-8"
            try:
                raw = raw_bytes.decode("utf-8", errors="strict")
            except UnicodeDecodeError:
                # Объявленная кодировка не UTF-8 (или UTF-8 не подходит побайтово) —
                # используем то, что реально объявлено в файле (обычно windows-1251).
                # Иначе utf-8 errors='ignore' молча роняет кириллицу, оставляя
                # <author>/<book-title> пустыми — см. docs/quality-roadmap.md, баг №48.
                try:
                    raw = raw_bytes.decode(declared_enc, errors="strict")
                except (LookupError, UnicodeDecodeError):
                    raw = raw_bytes.decode("cp1251", errors="replace")
            # Файл всегда записывается как UTF-8 (см. write_text ниже) — декларация
            # должна совпадать, иначе выходит файл с несовпадающей меткой кодировки.
            raw = re.sub(
                r'(<\?xml[^>]*encoding\s*=\s*["\'])[^"\']+(["\'])',
                r'\g<1>utf-8\g<2>', raw, count=1, flags=re.IGNORECASE,
            )
            stripped = strip_fb2(raw)
            out_path = dst_dir / f.relative_to(src_dir)
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(stripped, encoding="utf-8")
            total_in += len(raw.encode("utf-8"))
            total_out += len(stripped.encode("utf-8"))
            total_files += 1
        print(f"{rel}: {len(fb2_files)} files")

    print(f"\nTOTAL: {total_files} files, {total_in / 1024:.0f} KB -> {total_out / 1024:.0f} KB")


if __name__ == "__main__":
    main()
